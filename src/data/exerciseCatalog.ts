import type { EquipmentType, Exercise, MediaRef, MuscleGroup } from '@/types';
import { DEFAULT_MEDIA } from '@/types';

/**
 * 內建動作目錄擴充。
 * 既有 id 留在 exercises.ts，這裡只追加新動作，避免改到使用者已存的 session id。
 * 名稱刻意避開力量軌關鍵字（臥推／推胸／深蹲／硬舉／肩推），
 * 配件動作才不會被 getLiftFamily 的名稱比對算進四大項。
 * 沒有圖片、沒有圖片網址。
 */
interface CatalogSpec {
  id: string;
  name: string;
  muscleGroup: MuscleGroup;
  secondaryGroups?: MuscleGroup[];
  equipmentType: EquipmentType;
  equipmentId: string;
  muscleGroupDesc: string;
  equipmentDesc: string;
  cues: [string, string, string];
  tips: [string, string, string];
}

function toExercise(spec: CatalogSpec): Exercise {
  const steps = [
    spec.cues[0],
    spec.cues[1],
    spec.cues[2],
    '控制回到起始位置，再開始下一次',
  ];
  return {
    id: spec.id,
    name: spec.name,
    muscleGroup: spec.muscleGroup,
    category: spec.muscleGroup,
    secondaryGroups: spec.secondaryGroups,
    equipmentType: spec.equipmentType,
    equipmentId: spec.equipmentId,
    muscleGroupDesc: spec.muscleGroupDesc,
    equipmentDesc: spec.equipmentDesc,
    equipment: spec.equipmentDesc,
    isCustom: false,
    steps,
    instructions: steps,
    tips: spec.tips,
    media: { ...DEFAULT_MEDIA } as MediaRef,
  };
}

